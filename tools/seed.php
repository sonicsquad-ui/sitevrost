function wjson(string $name, $data): void {
    global $ROOT;
    $dir = $ROOT . '/data';
    if (!is_dir($dir)) mkdir($dir, 0755, true);
    if (!is_dir($dir . '/sessions')) mkdir($dir . '/sessions', 0755, true);
    file_put_contents($dir . '/' . $name . '.json',
        json_encode($data, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES | JSON_PRETTY_PRINT), LOCK_EX);
    echo "data/{$name}.json\n";
}

